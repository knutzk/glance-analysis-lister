"""Identify the generator checkout or the revision recorded when packaging it."""

import json
import logging
import re
import subprocess
from hashlib import sha256 as digest
from html import escape
from pathlib import Path

_REVISION = re.compile(r"[0-9a-f]{40}(?:-dirty)?")
REVISION_FILE = "_source_revision.txt"
logger = logging.getLogger(__name__)


def generator_revision(root=None):
    """Never mistake the consuming documentation repository for the generator."""
    root = Path(root) if root is not None else Path(__file__).resolve().parents[1]
    if (root / ".git").exists():
        try:

            def git(*arguments):
                return subprocess.check_output(
                    ["git", "-C", str(root), *arguments],
                    text=True,
                    stderr=subprocess.DEVNULL,
                    timeout=5,
                ).strip()

            if Path(git("rev-parse", "--show-toplevel")).resolve() == root.resolve():
                commit = git("rev-parse", "HEAD")
                if _REVISION.fullmatch(commit):
                    # Include new source files, but not unrelated local dotfiles.
                    tracked = git("status", "--porcelain", "--untracked-files=no")
                    new_source = git(
                        "ls-files",
                        "--others",
                        "--exclude-standard",
                        "--",
                        "analysis_lister",
                        "setup.py",
                    )
                    return commit + ("-dirty" if tracked or new_source else "")
        except (OSError, subprocess.SubprocessError):
            pass
    recorded = root / "analysis_lister" / REVISION_FILE
    if recorded.is_file():
        revision = recorded.read_text(encoding="utf-8").strip()
        if _REVISION.fullmatch(revision):
            return revision
    return "unknown"


def json_fingerprint(value):
    """Hash canonical UTF-8 JSON; dictionary order is irrelevant, list order is not."""
    raw = json.dumps(
        value,
        sort_keys=True,
        ensure_ascii=False,
        separators=(",", ":"),
        allow_nan=False,
    )
    return digest(raw.encode("utf-8")).hexdigest()


def generator_fingerprint(package_dir=None):
    """Identify Python, validation-schema and browser contents, including local edits.

    Use relative names and file bytes, not paths, mtimes, bytecode or Git metadata.
    Shared data dictionaries are already embedded in the curated snapshot;
    the effective group profile is fingerprinted separately.
    """
    root = (
        Path(package_dir)
        if package_dir is not None
        else Path(__file__).resolve().parent
    )
    paths = set(root.rglob("*.py"))
    # These ignored experimental modules are outside the maintained distribution.
    paths.difference_update(root / name for name in ("events.py", "event_labels.py"))
    paths.update((root / "registry/schemas").glob("*.json"))
    for suffix in ("*.js", "*.css"):
        paths.update((root / "views/assets").glob(suffix))
    return json_fingerprint(
        {
            path.relative_to(root).as_posix(): digest(path.read_bytes()).hexdigest()
            for path in sorted(paths)
            if "__pycache__" not in path.relative_to(root).parts
        }
    )


def generator_metadata():
    """Record code identity without tying generated data to a format version."""
    return {
        "name": "glance-analysis-lister",
        "git_commit": generator_revision(),
        "content_sha256": generator_fingerprint(),
    }


def warn_generator_mismatch(data, *, label):
    """Advise on missing/different provenance; never reject otherwise valid data.

    Compare contents rather than Git revisions or worktree paths, so identical
    code in another checkout or installation matches. Do not log input metadata:
    even supposedly descriptive fields may contain private or malformed values.
    """
    metadata = data.get("generator")
    fingerprint = metadata.get("content_sha256") if isinstance(metadata, dict) else None
    if (
        not isinstance(metadata, dict)
        or metadata.get("name") != "glance-analysis-lister"
        or not isinstance(fingerprint, str)
        or re.fullmatch(r"[0-9a-f]{64}", fingerprint) is None
    ):
        logger.warning(
            "%s has missing or unrecognised generator metadata; continuing after "
            "validation. Regenerate it with the current package if problems occur.",
            label,
        )
    elif fingerprint != generator_fingerprint():
        logger.warning(
            "%s was generated by different package code; continuing after "
            "validation. Regenerate it with the current package if problems occur.",
            label,
        )


def markdown_provenance(
    content, *, revision, snapshot, sha256, profile_sha256=None, generator_sha256=None
):
    """Put provenance after YAML front matter, without a generation timestamp."""
    filename = (
        escape(Path(snapshot).name)
        .replace("--", "&#45;&#45;")
        .replace("\n", " ")
        .replace("\r", " ")
    )
    header = (
        "<!--\n"
        "Automatically generated by glance-analysis-lister. Do not edit directly.\n"
        f"Generator Git commit: {revision}\n"
        f"Registry snapshot: {filename}\n"
        f"Registry SHA-256: {sha256}\n"
        + (f"Render profile SHA-256: {profile_sha256}\n" if profile_sha256 else "")
        + (
            f"Generator contents SHA-256: {generator_sha256}\n"
            if generator_sha256
            else ""
        )
        + "Regenerate with: analysis-lister render-group\n"
        "-->\n\n"
    )
    if content.startswith("---\n"):
        end = content.find("\n---\n", 4)
        if end != -1:
            end += len("\n---\n")
            return content[:end] + "\n" + header + content[end:].lstrip("\n")
    return header + content


def asset_provenance(content, *, revision):
    """Preserve upstream copyright/licence notices and identify copied assets."""
    header = (
        "/* Automatically supplied by glance-analysis-lister.\n"
        f" * Source Git commit: {revision}\n"
        " * Do not edit this copy; update the package asset and regenerate. */\n"
    )
    if content.startswith("/*"):
        end = content.find("*/")
        if end != -1:
            end += 2
            return content[:end] + "\n\n" + header + content[end:].lstrip("\n")
    return header + content
