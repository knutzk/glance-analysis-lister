"""Identify the generator checkout or the revision recorded when packaging it."""

import re
import subprocess
from html import escape
from pathlib import Path

_REVISION = re.compile(r"[0-9a-f]{40}(?:-dirty)?")
REVISION_FILE = "_source_revision.txt"


def generator_revision(root=None):
    """Never mistake the consuming documentation repository for the generator."""
    root = Path(root) if root is not None else Path(__file__).resolve().parents[1]
    if (root / ".git").exists():
        try:

            def git(*arguments):
                return subprocess.check_output(
                    ["git", "-C", str(root), *arguments],
                    text=True,
                    stderr=subprocess.DEVNULL,
                    timeout=5,
                ).strip()

            if Path(git("rev-parse", "--show-toplevel")).resolve() == root.resolve():
                commit = git("rev-parse", "HEAD")
                if _REVISION.fullmatch(commit):
                    # Include new source files, but not unrelated local dotfiles.
                    tracked = git("status", "--porcelain", "--untracked-files=no")
                    new_source = git(
                        "ls-files",
                        "--others",
                        "--exclude-standard",
                        "--",
                        "analysis_lister",
                        "setup.py",
                    )
                    return commit + ("-dirty" if tracked or new_source else "")
        except (OSError, subprocess.SubprocessError):
            pass
    recorded = root / "analysis_lister" / REVISION_FILE
    if recorded.is_file():
        revision = recorded.read_text(encoding="utf-8").strip()
        if _REVISION.fullmatch(revision):
            return revision
    return "unknown"


def markdown_provenance(content, *, revision, snapshot, sha256):
    """Put provenance after YAML front matter, without a generation timestamp."""
    filename = (
        escape(Path(snapshot).name)
        .replace("--", "&#45;&#45;")
        .replace("\n", " ")
        .replace("\r", " ")
    )
    header = (
        "<!--\n"
        "Automatically generated by glance-analysis-lister. Do not edit directly.\n"
        f"Generator Git commit: {revision}\n"
        f"Registry snapshot: {filename}\n"
        f"Registry SHA-256: {sha256}\n"
        "Regenerate with: analysis-lister render-group\n"
        "-->\n\n"
    )
    if content.startswith("---\n"):
        end = content.find("\n---\n", 4)
        if end != -1:
            end += len("\n---\n")
            return content[:end] + "\n" + header + content[end:].lstrip("\n")
    return header + content


def asset_provenance(content, *, revision):
    """Preserve upstream copyright/licence notices and identify copied assets."""
    header = (
        "/* Automatically supplied by glance-analysis-lister.\n"
        f" * Source Git commit: {revision}\n"
        " * Do not edit this copy; update the package asset and regenerate. */\n"
    )
    if content.startswith("/*"):
        end = content.find("*/")
        if end != -1:
            end += 2
            return content[:end] + "\n\n" + header + content[end:].lstrip("\n")
    return header + content
